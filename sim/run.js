// Writes the M0 economy report: docs/economy/report.md plus CSV files. Run: node sim/run.js
const fs = require('fs');
const path = require('path');
const E = require('../js/economy.js');
const S = require('./sim.js');
const C = E.C;

const OUT = path.join(__dirname, '..', 'docs', 'economy');
const TPS = [3, 5, 8];
const MINUTES = [10, 15, 20, 30];
const DAYS = 14;

const fmtS = (s) => (s === undefined || s === null ? 'not reached' : s < 120 ? `${s.toFixed(1)} s` : `${(s / 60).toFixed(1)} min`);
const pct = (x) => `${Math.round(x * 100)}%`;
const csv = (rows) => {
  const keys = Object.keys(rows[0]);
  return [keys.join(','), ...rows.map((r) => keys.map((k) => r[k]).join(','))].join('\n') + '\n';
};

fs.mkdirSync(OUT, { recursive: true });
const md = [];
md.push('# M0 economy report (generated)');
md.push('');
md.push('Generated by `node sim/run.js` from `js/economy.js`. Do not edit by hand; the analysis is in `docs/economy/README.md`.');
md.push('Child model: steady taps per second, buys the best upgrade it can afford after every Titan, retries a missed boss when');
md.push('the squad looks strong enough (or after 60 s), one session a day, the rest of the day away.');
md.push('');

// Constants
md.push('## Constants');
md.push('');
md.push('| Constant | Value |');
md.push('|---|---|');
for (const [k, v] of Object.entries(C)) if (typeof v === 'number') md.push(`| \`${k}\` | ${v} |`);
md.push('');
md.push('| Hero | DPS at level 1 | First level cost |');
md.push('|---|---|---|');
for (const id of C.HERO_ORDER) md.push(`| ${id} | ${C.HEROES[id].dps0} | ${C.HEROES[id].c0} |`);
md.push('');
md.push('| Dream upgrade | Boosts | x per level | Cost of level 1, 2, 3, 5, 10 |');
md.push('|---|---|---|---|');
for (const id of C.DREAM_ORDER) {
  const u = C.DREAM_UPGRADES[id];
  md.push(`| ${id} | ${u.what} | ${1 + u.step} | ${[0, 1, 2, 4, 9].map((l) => E.dreamCost(id, l)).join(', ')} |`);
}
md.push('');
md.push(`Dreams for the best stage of a run: ${[20, 25, 30, 40, 50, 60].map((s) => `stage ${s}: ${E.dreams(s)}`).join(', ')}.`);
md.push('');

// Day 1
md.push('## Day 1: first hour of a brand-new player');
md.push('');
md.push('| Taps/s | First kill | First boss (10) beaten | Stage 20 | Stage 30 | Stage 50 | Dreams first on offer | Progress stalls | Best stage after 60 min |');
md.push('|---|---|---|---|---|---|---|---|---|');
const day1 = [];
for (const tps of TPS) {
  const p = S.play(E.newRun(), 3600, { tps, sampleEvery: 60 });
  const r = p.ev.reach;
  const stall = S.plateau(p.samples.filter((s) => s.t <= 1800), p.samples.find((s) => s.t === 1800).maxStage);
  md.push(`| ${tps} | ${fmtS(p.ev.firstKill)} | ${fmtS(p.ev.beat[10])} | ${fmtS(r[20])} | ${fmtS(r[30])} | ${fmtS(r[50])} | ${fmtS(r[C.D_MIN])} | minute ${stall} | ${p.run.maxStage} |`);
  for (const s of p.samples) day1.push({ tps, minute: s.t / 60, stage: s.stage, maxStage: s.maxStage, dreamsOnOffer: s.dreams, damagePerSec: s.dps.toFixed(1) });
}
md.push('');
md.push('"Progress stalls": first minute after which the best stage did not grow again in the first 30 minutes.');
md.push('Past that point more play earns no more Dreams, so it is the good moment for Bedtime.');
md.push('');
md.push('Dreams on offer by minute (5 taps/s):');
md.push('');
const d1 = day1.filter((x) => x.tps === 5);
md.push('| Minute | ' + [5, 10, 15, 20, 30, 45, 60].join(' | ') + ' |');
md.push('|---|' + '---|'.repeat(7));
md.push('| Best stage | ' + [5, 10, 15, 20, 30, 45, 60].map((m) => d1.find((x) => x.minute === m).maxStage).join(' | ') + ' |');
md.push('| Dreams | ' + [5, 10, 15, 20, 30, 45, 60].map((m) => d1.find((x) => x.minute === m).dreamsOnOffer).join(' | ') + ' |');
md.push('');
fs.writeFileSync(path.join(OUT, 'day1.csv'), csv(day1));

// 14 days
const all = [];
const run = (o) => {
  const rows = S.days(Object.assign({ n: DAYS }, o));
  const base = S.days(Object.assign({ n: DAYS, offline: false }, o));
  rows.forEach((r, i) => {
    r.offlineFrom = o.offlineFrom;
    r.stagesFromOffline = r.bestStage - base[i].bestStage;
    r.offlineProgressShare = +((r.bestStage - base[i].bestStage) / (r.bestStage - 1)).toFixed(3);
    r.offlineShare = +r.offlineShare.toFixed(3);
    r.activeStars = Math.round(r.activeStars);
  });
  all.push(...rows);
  return rows;
};

for (const offlineFrom of ['before', 'after']) {
  md.push(`## 14 days, Bedtime every evening, offline counted from the squad ${offlineFrom === 'before' ? 'BEFORE' : 'AFTER'} the reset`);
  md.push('');
  md.push('Best stage ever, by day (5 taps/s). World = 30 stages.');
  md.push('');
  md.push('| Minutes a day | ' + Array.from({ length: DAYS }, (_, i) => `D${i + 1}`).join(' | ') + ' | World 2 on day | World 3 on day |');
  md.push('|---|' + '---|'.repeat(DAYS + 2));
  for (const minutes of MINUTES) {
    const rows = run({ minutes, tps: 5, policy: 'nightly', offlineFrom });
    const w = (k) => (rows.find((r) => r.bestStage > 30 * (k - 1)) || {}).day || '-';
    md.push(`| ${minutes} | ${rows.map((r) => r.bestStage).join(' | ')} | ${w(2)} | ${w(3)} |`);
  }
  md.push('');
  if (offlineFrom === 'before') {
    md.push('Share of progress that came from offline earnings (best stage with offline vs the same days without it):');
    md.push('');
    md.push('| Minutes a day | ' + Array.from({ length: DAYS }, (_, i) => `D${i + 1}`).join(' | ') + ' | Max |');
    md.push('|---|' + '---|'.repeat(DAYS + 1));
    for (const minutes of MINUTES) {
      const rows = all.filter((r) => r.minutes === minutes && r.offlineFrom === 'before' && r.policy === 'nightly' && r.tps === 5);
      md.push(`| ${minutes} | ${rows.map((r) => pct(r.offlineProgressShare)).join(' | ')} | ${pct(Math.max(...rows.map((r) => r.offlineProgressShare)))} |`);
    }
    md.push('');
    md.push('Good Bedtime moment by day (minute of the session after which the run stopped growing; 20 min a day):');
    md.push('');
    const rows = all.filter((r) => r.minutes === 20 && r.offlineFrom === 'before' && r.policy === 'nightly' && r.tps === 5);
    md.push('| ' + rows.map((r) => `D${r.day}`).join(' | ') + ' |');
    md.push('|' + '---|'.repeat(rows.length));
    md.push('| ' + rows.map((r) => (r.plateauMin === null ? 'end' : r.plateauMin)).join(' | ') + ' |');
    md.push('');
    md.push('Dreams earned at each Bedtime (20 min a day): ' + rows.map((r) => r.dreamsGot).join(', ') + '.');
    md.push('');
  } else {
    md.push('With this rule a nightly Bedtime resets the squad before the night, so offline earnings are always 0.');
    md.push('');
  }
}

md.push('## Taps per second, 14 days at 20 minutes a day (offline from the squad before Bedtime)');
md.push('');
md.push('| Taps/s | ' + Array.from({ length: DAYS }, (_, i) => `D${i + 1}`).join(' | ') + ' |');
md.push('|---|' + '---|'.repeat(DAYS));
for (const tps of TPS) {
  const rows = run({ minutes: 20, tps, policy: 'nightly', offlineFrom: 'before', tag: 'tps' });
  md.push(`| ${tps} | ${rows.map((r) => r.bestStage).join(' | ')} |`);
}
md.push('');

md.push('## Bedtime every evening vs only when it pays (15 minutes a day, 5 taps/s)');
md.push('');
md.push('"smart": Bedtime only when it adds at least half of all Dreams so far; other evenings say Goodnight and keep the run.');
md.push('');
md.push('| Policy | ' + Array.from({ length: DAYS }, (_, i) => `D${i + 1}`).join(' | ') + ' | Bedtimes |');
md.push('|---|' + '---|'.repeat(DAYS + 1));
for (const policy of ['nightly', 'smart']) {
  const rows = run({ minutes: 15, tps: 5, policy, offlineFrom: 'before', tag: 'policy' });
  md.push(`| ${policy} | ${rows.map((r) => r.bestStage).join(' | ')} | ${rows.filter((r) => r.bedtime).length} |`);
}
md.push('');

for (const r of all) delete r.tag;
fs.writeFileSync(path.join(OUT, 'days.csv'), csv(all));
fs.writeFileSync(path.join(OUT, 'report.md'), md.join('\n'));
console.log(`wrote ${path.relative(process.cwd(), OUT)}/report.md, day1.csv, days.csv`);
